/// Distinct 5x6 silhouette status glyphs for accessibility and at-a-glance scanning.
///
/// Ported from `STATUS_GLYPHS` in `mockups/plate.js`:
/// - asks: `?`
/// - failed: `X`
/// - quiet: small resting dot
/// - working: solid live block
/// - unknown: horizontal dash
pub fn get_status_glyph(status: &str) -> &'static [&'static str] {
    match status {
        "asks" => &[".###.", "#...#", "...#.", "..#..", ".....", "..#.."],
        "failed" | "fails" => &[".....", "#...#", ".#.#.", "..#..", ".#.#.", "#...#"],
        "quiet" => &[".....", ".....", "..##.", "..##.", ".....", "....."],
        "working" => &[".....", ".###.", ".###.", ".###.", ".###.", "....."],
        _ => &[".....", ".....", "#####", ".....", ".....", "....."],
    }
}
